#!/usr/bin/env node
// Regenerate the Codex app-server protocol types from the installed `codex` CLI:
//   pnpm --filter @codeden/providers codex:protocol
// Writes src/codex/protocol/ (generated, not linted) and records the Codex version.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(root, "src", "codex", "protocol");

/** Resolve how to run codex without a shell (npm .cmd shims are unwrapped to node <script>). */
function codexCommand() {
  const dirs = (process.env.PATH ?? "").split(path.delimiter).filter(Boolean);
  const exts = process.platform === "win32" ? [".exe", ".cmd", ""] : [""];
  for (const dir of dirs) {
    for (const ext of exts) {
      const file = path.join(dir, `codex${ext}`);
      if (!existsSync(file)) continue;
      if (ext === ".cmd") {
        const m = /"%~?dp0%?\\?([^"%]+?\.[cm]?js)"/i.exec(readFileSync(file, "utf8"));
        if (m?.[1]) return [process.execPath, [path.resolve(dir, m[1])]];
        continue;
      }
      return [file, []];
    }
  }
  throw new Error("codex not found on PATH");
}

const [file, pre] = codexCommand();
const version = execFileSync(file, [...pre, "--version"], { encoding: "utf8" }).trim();
rmSync(out, { recursive: true, force: true });
execFileSync(file, [...pre, "app-server", "generate-ts", "--out", out], { stdio: "inherit" });
writeFileSync(
  path.join(out, "VERSION.ts"),
  `// Generated by scripts/generate-codex-protocol.mjs. Do not edit.\nexport const CODEX_PROTOCOL_VERSION = ${JSON.stringify(version)};\n`,
);
console.log(
  `Generated Codex protocol types for ${version} in ${path.relative(process.cwd(), out)}`,
);
